// Generates every platform output from tokens/source.mjs.
//   src/tokens/tokens.css        CSS custom properties (light, dark) + text utility classes
//   src/tokens/tokens.ts         Typed JS object + string-literal unions for props
//   tokens/dist/tokens.json      W3C DTCG format (Tokens Studio / Style Dictionary compatible)
// Run: npm run tokens
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as T from '../tokens/source.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p, s) => { const f = resolve(root, p); mkdirSync(dirname(f), { recursive: true }); writeFileSync(f, s); console.log('  wrote', p); };
const P = T.PREFIX;
const kebab = (s) => s.replace(/\//g, '-');
const camel = (s) => s.replace(/[/-](\w)/g, (_, c) => c.toUpperCase());
const hexOf = (ref) => { if (ref.startsWith('rgba')) return ref; const [f, s] = ref.split('.'); return T.primitives[f][s]; };
const primVar = (ref) => ref.startsWith('rgba') ? ref : `var(--${P}-${ref.replace('.', '-')})`;
const shadow = (layers) => layers.map((l) => `0 ${l.y}px ${l.blur}px ${l.spread}px ${l.color}`).join(', ');
const header = '/* AUTO-GENERATED by scripts/build-tokens.mjs — edit tokens/source.mjs instead. */\n';

// ── CSS
let css = header + ':root {\n';
for (const [fam, steps] of Object.entries(T.primitives)) for (const [s, h] of Object.entries(steps)) css += `  --${P}-${fam}-${s}: ${h};\n`;
css += '\n';
for (const [n, [l]] of Object.entries(T.semantic)) css += `  --${P}-color-${kebab(n)}: ${primVar(l)};\n`;
css += '\n';
for (const [k, v] of Object.entries(T.spacing)) css += `  --${P}-space-${k}: ${v / 16}rem;\n`;
for (const [k, v] of Object.entries(T.radius)) css += `  --${P}-radius-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(T.borderWidth)) css += `  --${P}-border-width-${k}: ${v}px;\n`;
for (const [k, v] of Object.entries(T.size)) css += `  --${P}-size-${k}: ${v / 16}rem;\n`;
for (const [k, v] of Object.entries(T.elevation)) css += `  --${P}-elevation-${k}: ${shadow(v)};\n`;
for (const [k, v] of Object.entries(T.motion.duration)) css += `  --${P}-duration-${k}: ${v}ms;\n`;
for (const [k, v] of Object.entries(T.motion.easing)) css += `  --${P}-ease-${k}: ${v};\n`;
for (const [k, v] of Object.entries(T.fontFamily)) css += `  --${P}-font-${k}: ${v.stack};\n`;
for (const [n, s] of Object.entries(T.typography)) {
  const k = kebab(n);
  css += `  --${P}-text-${k}-size: ${s.size / 16}rem;\n  --${P}-text-${k}-line: ${s.line / 16}rem;\n`;
}
css += '  color-scheme: light;\n}\n\n';
const modeBlock = (sel, mode) => { const i = mode === 'dark' ? 1 : 0; let b = `${sel} {\n`; for (const [n, pair] of Object.entries(T.semantic)) b += `  --${P}-color-${kebab(n)}: ${primVar(pair[i])};\n`; b += `  color-scheme: ${mode};\n}\n`; return b; };
const darkBlock = (sel) => modeBlock(sel, 'dark');
css += darkBlock('[data-theme="dark"], .kv-theme-dark') + '\n';
css += `@media (prefers-color-scheme: dark) {\n  ${darkBlock(':root:not([data-theme="light"])').replace(/\n/g, '\n  ')}\n}\n\n`;
// Light must be re-declared on [data-theme="light"] too, or a light section nested inside a dark
// ancestor (Storybook docs, a light card on a dark page) just inherits the dark values.
css += modeBlock('[data-theme="light"], .kv-theme-light', 'light') + '\n';
css += `@media (prefers-reduced-motion: reduce) {\n  :root { ${Object.keys(T.motion.duration).map((k) => `--${P}-duration-${k}: 0ms;`).join(' ')} }\n}\n\n`;
// Text utility classes
for (const [n, s] of Object.entries(T.typography)) {
  const k = kebab(n);
  css += `.${P}-text-${k} { font-family: var(--${P}-font-${s.family}); font-size: var(--${P}-text-${k}-size); line-height: var(--${P}-text-${k}-line); font-weight: ${s.weight}; letter-spacing: ${s.tracking / 100}em;${s.upper ? ' text-transform: uppercase;' : ''}${s.tabular ? ' font-variant-numeric: tabular-nums;' : ''} }\n`;
}
out('src/tokens/tokens.css', css);

// ── TypeScript
const ts = `${header.replace('/*', '//').replace(' */', '')}
export const prefix = '${P}' as const;
export const primitives = ${JSON.stringify(T.primitives, null, 2)} as const;
/** Semantic colors: [light, dark] resolved hex (or rgba). Prefer cssVar() in web code. */
export const colors = ${JSON.stringify(Object.fromEntries(Object.entries(T.semantic).map(([n, [l, d]]) => [n, { light: hexOf(l), dark: hexOf(d) }])), null, 2)} as const;
export const spacing = ${JSON.stringify(T.spacing)} as const;
export const radius = ${JSON.stringify(T.radius)} as const;
export const size = ${JSON.stringify(T.size)} as const;
export const motion = ${JSON.stringify(T.motion)} as const;
export const typography = ${JSON.stringify(T.typography, null, 2)} as const;
export const fontFamily = ${JSON.stringify(T.fontFamily)} as const;

export type ColorToken = keyof typeof colors;
export type SpaceToken = keyof typeof spacing;
export type RadiusToken = keyof typeof radius;
export type TextVariant = keyof typeof typography;

/** cssVar('bg/brand') → 'var(--${P}-color-bg-brand)' */
export const cssVar = (token: ColorToken) => \`var(--${P}-color-\${token.replace('/', '-')})\`;
export const space = (token: SpaceToken) => \`var(--${P}-space-\${token})\`;
export const textClass = (variant: TextVariant) => \`${P}-text-\${variant.replace('/', '-')}\`;
`;
out('src/tokens/tokens.ts', ts);

// ── DTCG JSON
const dtcg = { primitive: {}, color: { light: {}, dark: {} }, space: {}, radius: {}, typography: {} };
for (const [fam, steps] of Object.entries(T.primitives)) { dtcg.primitive[fam] = {}; for (const [s, h] of Object.entries(steps)) dtcg.primitive[fam][s] = { $type: 'color', $value: h }; }
const ref = (r) => r.startsWith('rgba') ? r : `{primitive.${r}}`;
for (const [n, [l, d]] of Object.entries(T.semantic)) { const [g, k] = n.split('/'); (dtcg.color.light[g] ||= {})[k] = { $type: 'color', $value: ref(l) }; (dtcg.color.dark[g] ||= {})[k] = { $type: 'color', $value: ref(d) }; }
for (const [k, v] of Object.entries(T.spacing)) dtcg.space[k] = { $type: 'dimension', $value: `${v}px` };
for (const [k, v] of Object.entries(T.radius)) dtcg.radius[k] = { $type: 'dimension', $value: `${v}px` };
for (const [n, s] of Object.entries(T.typography)) dtcg.typography[kebab(n)] = { $type: 'typography', $value: { fontFamily: T.fontFamily[s.family].name, fontWeight: s.weight, fontSize: `${s.size}px`, lineHeight: `${s.line}px`, letterSpacing: `${s.tracking / 100}em` } };
out('tokens/dist/tokens.json', JSON.stringify(dtcg, null, 2));


console.log('✓ tokens built');
